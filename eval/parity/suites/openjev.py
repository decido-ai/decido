"""OpenJev static text group (19 tasks), re-implemented from AlexWortega/openjev code/eval.py (MIT,
revision a20448012c213128955ca0c693e7c943865cab77) so that the same items are scored.

Protocol (comparable with AutoTrust's Jev run, which "takes the option with the highest entailment
probability, ties going to the first option"):
  * NLI classification tasks: one request per (premise, hypothesis); 3-way NLI choice; argmax.
    SciTail is 2-class: any non-entailment prediction counts as not-entailed.
  * Multiple-choice rerank tasks: one NLI request per option, premise = question,
    hypothesis = task template(option); prediction = argmax_j P_j(entailment), ties -> first option.
  * Group score = mean of 19 task accuracies, with MNLI matched/mismatched averaged first.

GSM8K nli_rerank@4 needs the frozen candidate pool generated by the OpenJev author with a local
Qwen3.5 llama-server (data/gsm8k_cands.jsonl). That file is not published, so the task is reported
as missing unless a pool is placed at data/raw/parity/openjev-gsm8k/gsm8k_cands.jsonl.
"""

from __future__ import annotations

import csv
import random
import re

from eval.parity.common import HF_CACHE, NLI_LABELS, RAW

CACHE = str(HF_CACHE / "datasets")

TASKS_19 = ["mnli", "anli_r1", "anli_r2", "anli_r3", "wanli", "scitail", "control",
            "arc_easy", "arc_challenge", "winogrande", "gsm8k_mc4", "gsm8k_mc10", "gpqa", "gpqa_fewshot",
            "chess", "hellaswag", "mmlu", "mmlu_fewshot", "gsm8k_rerank4"]

NLI_SETS = {  # name -> (repo, config, split, premise col, hypothesis col, label col)
    "anli_r1": ("facebook/anli", None, "test_r1", "premise", "hypothesis", "label"),
    "anli_r2": ("facebook/anli", None, "test_r2", "premise", "hypothesis", "label"),
    "anli_r3": ("facebook/anli", None, "test_r3", "premise", "hypothesis", "label"),
    "wanli": ("alisawuffles/WANLI", None, "test", "premise", "hypothesis", "gold"),
    "scitail": ("allenai/scitail", "snli_format", "test", "sentence1", "sentence2", "gold_label"),
    "control": ("tasksource/ConTRoL-nli", None, "test", "premise", "hypothesis", "label"),
}
_NAME2LAB = {"contradiction": "contradiction", "entailment": "entailment", "neutral": "neutral",
             "entails": "entailment", "not_entailment": "neutral"}


def _load(repo, cfg=None, split=None):
    from datasets import load_dataset
    if cfg:
        return load_dataset(repo, cfg, split=split, cache_dir=CACHE)
    return load_dataset(repo, split=split, cache_dir=CACHE)


def _nli_item(task, idx, premise, hypothesis, label, two_class=False):
    return {"uid": f"{task}/{idx}", "suite": "openjev", "task": task, "group": None, "rule": "nli_cls",
            "nli": {"premise": premise, "hyps": [hypothesis]}, "golds": {"0:relation": label},
            "meta": {"two_class": two_class}}


def _mc_item(task, idx, q, opts, gold, hyp_tmpl):
    return {"uid": f"{task}/{idx}", "suite": "openjev", "task": task, "group": None, "rule": "nli_rerank",
            "nli": {"premise": q, "hyps": [hyp_tmpl(o) for o in opts]}, "golds": {"rerank": int(gold)},
            "meta": {"n_options": len(opts)}}


def mnli_items():
    native = {0: "entailment", 1: "neutral", 2: "contradiction"}
    out = []
    for split in ("validation_matched", "validation_mismatched"):
        ds = _load("nyu-mll/multi_nli", split=split)
        for i, ex in enumerate(ds):
            if ex["label"] not in (0, 1, 2):
                continue
            it = _nli_item("mnli", f"{split}/{i}", ex["premise"], ex["hypothesis"], native[ex["label"]])
            it["meta"]["mnli_split"] = split
            out.append(it)
    return out


def nli_set_items(name):
    repo, cfg, split, pc, hc, lc = NLI_SETS[name]
    ds = _load(repo, cfg, split)
    feat = ds.features[lc]
    pairs = []
    for i, ex in enumerate(ds):
        v = ex[lc]
        nm = feat.names[v] if isinstance(v, int) and hasattr(feat, "names") else v
        if not isinstance(nm, str) or nm.strip().lower() not in _NAME2LAB:
            continue
        pairs.append((i, ex[pc], ex[hc], _NAME2LAB[nm.strip().lower()]))
    two_class = len({p[3] for p in pairs}) == 2
    return [_nli_item(name, i, p, h, lab, two_class) for i, p, h, lab in pairs]


DEFAULT_HYP = lambda o: f"The correct answer is: {o}"  # noqa: E731
FEWSHOT_HYP = lambda o: f"Answer: {o}"  # noqa: E731


def _with_demos(q, demos):
    return "\n\n".join(f"{dq}\nAnswer: {da}" for dq, da in demos) + "\n\n" + q


def gpqa_items(fewshot=0, seed=0):
    path = RAW / "gpqa" / "dataset" / "gpqa_diamond.csv"
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    base = []
    for ex in rows:
        opts = [ex["Correct Answer"], ex["Incorrect Answer 1"], ex["Incorrect Answer 2"], ex["Incorrect Answer 3"]]
        base.append({"q": ex["Question"].strip(), "opts": [o.strip() for o in opts], "gold": 0})
    name = "gpqa_fewshot" if fewshot else "gpqa"
    if not fewshot:
        return [_mc_item(name, i, b["q"], b["opts"], 0, DEFAULT_HYP) for i, b in enumerate(base)]
    rng = random.Random(seed)
    out = []
    for i, it in enumerate(base):
        pool = [j for j in range(len(base)) if j != i]
        demos = [(base[j]["q"], base[j]["opts"][base[j]["gold"]]) for j in rng.sample(pool, fewshot)]
        out.append(_mc_item(name, i, _with_demos(it["q"], demos), it["opts"], it["gold"], FEWSHOT_HYP))
    return out


def mmlu_items(fewshot=0):
    ds = _load("cais/mmlu", "all", "test")
    dev = {}
    if fewshot:
        for ex in _load("cais/mmlu", "all", "dev"):
            dev.setdefault(ex["subject"], []).append((ex["question"].strip(), ex["choices"][int(ex["answer"])].strip()))
    name = "mmlu_fewshot" if fewshot else "mmlu"
    out = []
    for i, ex in enumerate(ds):
        q, opts, g = ex["question"].strip(), [c.strip() for c in ex["choices"]], int(ex["answer"])
        if fewshot:
            out.append(_mc_item(name, i, _with_demos(q, dev[ex["subject"]][:fewshot]), opts, g, FEWSHOT_HYP))
        else:
            out.append(_mc_item(name, i, q, opts, g, DEFAULT_HYP))
        out[-1]["meta"]["subject"] = ex["subject"]
    return out


def arc_items(cfg):
    ds = _load("allenai/ai2_arc", cfg, "test")
    name = "arc_easy" if cfg == "ARC-Easy" else "arc_challenge"
    out = []
    for i, ex in enumerate(ds):
        labels = ex["choices"]["label"]
        if ex["answerKey"] not in labels:
            continue
        out.append(_mc_item(name, i, ex["question"].strip(), [t.strip() for t in ex["choices"]["text"]],
                            labels.index(ex["answerKey"]), DEFAULT_HYP))
    return out


def winogrande_items():
    ds = _load("allenai/winogrande", "winogrande_xl", "validation")
    out = []
    for i, ex in enumerate(ds):
        sent = ex["sentence"]
        opts = [ex["option1"], ex["option2"]]
        out.append(_mc_item("winogrande", i, sent, opts, int(ex["answer"]) - 1, lambda o, s=sent: s.replace("_", o)))
    return out


def hellaswag_items():
    ds = _load("Rowan/hellaswag", split="validation")
    out = []
    for i, ex in enumerate(ds):
        ctx = (ex["ctx_a"] + " " + ex["ctx_b"].capitalize()).strip() if ex["ctx_b"] else ex["ctx_a"].strip()
        out.append(_mc_item("hellaswag", i, f"{ex['activity_label']}: {ctx}", [e.strip() for e in ex["endings"]],
                            int(ex["label"]), lambda o: o))
    return out


NUM_RE = re.compile(r"-?\d[\d,]*\.?\d*")


def _extract_number(text):
    m = re.search(r"####\s*(-?[\d,]*\.?\d+)", text)
    if m:
        s = m.group(1)
    else:
        nums = NUM_RE.findall(text)
        if not nums:
            return None
        s = nums[-1]
    s = s.replace(",", "").rstrip(".")
    try:
        v = float(s)
    except ValueError:
        return None
    return str(int(v)) if v == int(v) else str(v)


def gsm8k_mc_items(k=4, seed=0):
    rng = random.Random(seed)
    ds = _load("openai/gsm8k", "main", "test")
    out = []
    for i, ex in enumerate(ds):
        g = _extract_number(ex["answer"])
        gv = float(g)
        cands = set()
        gen = [lambda: gv + rng.choice([1, 2, 3, 5, 10]), lambda: gv - rng.choice([1, 2, 3, 5, 10]), lambda: gv * 2,
               lambda: gv / 2, lambda: gv + rng.choice([4, 6, 7, 8, 9, 12, 15, 20, 25, 50]), lambda: gv * 10,
               lambda: gv * rng.choice([3, 4, 5]), lambda: gv - rng.choice([4, 6, 7, 8, 9, 12, 15, 20, 25, 50]),
               lambda: abs(gv) + rng.randint(100, 999)]
        gi = 0
        while len(cands) < k - 1 and gi < 200:
            v = gen[gi % len(gen)]()
            gi += 1
            vs = str(int(v)) if float(v) == int(v) else f"{v:.2f}"
            if vs != g and vs not in cands and v >= 0:
                cands.add(vs)
        opts = [g] + sorted(cands, key=lambda x: rng.random())
        order = list(range(len(opts)))
        rng.shuffle(order)
        opts = [opts[j] for j in order]
        out.append(_mc_item(f"gsm8k_mc{k}", i, ex["question"].strip(), opts, opts.index(g), lambda o: f"The answer is {o}."))
    return out


def chess_items(n=500, seed=0):
    import chess
    rng = random.Random(seed)
    out = []
    while len(out) < n:
        board = chess.Board()
        for _ in range(rng.randint(6, 40)):
            moves = list(board.legal_moves)
            if not moves or board.is_game_over():
                break
            board.push(rng.choice(moves))
        legal = list(board.legal_moves)
        if len(legal) < 2 or board.is_game_over():
            continue
        legal_san = {board.san(m) for m in legal}
        good = board.san(rng.choice(legal))
        bad = set()
        tries = 0
        while len(bad) < 3 and tries < 500:
            tries += 1
            sq = rng.choice([s for s in chess.SQUARES if board.piece_at(s) and board.piece_at(s).color == board.turn])
            piece = board.piece_at(sq)
            to = rng.choice(chess.SQUARES)
            if to == sq or (board.piece_at(to) and board.piece_at(to).color == board.turn):
                continue
            capture = board.piece_at(to) is not None
            if piece.piece_type == chess.PAWN:
                san = (chess.square_name(sq)[0] + "x" if capture else "") + chess.square_name(to)
            else:
                san = chess.piece_symbol(piece.piece_type).upper() + ("x" if capture else "") + chess.square_name(to)
            if san not in legal_san and san != good:
                bad.add(san)
        if len(bad) < 3:
            continue
        opts = [good] + sorted(bad)
        rng.shuffle(opts)
        pgn = chess.Board().variation_san(board.move_stack)
        q = (f"Chess position after the moves: {pgn}\nFEN: {board.fen()}\n"
             f"{'White' if board.turn else 'Black'} to move. Which of the following moves is legal in this position?")
        out.append(_mc_item("chess", len(out), q, opts, opts.index(good), DEFAULT_HYP))
    return out


def gsm8k_rerank_items(k=4):
    path = RAW / "openjev-gsm8k" / "gsm8k_cands.jsonl"
    if not path.exists():
        return []
    import json
    rows = [json.loads(line) for line in open(path)]
    out = []
    for i, r in enumerate(rows):
        samples = r["cands"][1:1 + k]
        correct = [j for j, c in enumerate(samples) if c["correct"]]
        it = _mc_item("gsm8k_rerank4", i, r["question"], [c["text"] for c in samples], correct[0] if correct else -1, lambda o: o)
        it["meta"]["correct_set"] = correct
        out.append(it)
    return out


def build_openjev(tasks=None) -> tuple[list[dict], dict]:
    tasks = tasks or TASKS_19
    builders = {
        "mnli": mnli_items, "anli_r1": lambda: nli_set_items("anli_r1"), "anli_r2": lambda: nli_set_items("anli_r2"),
        "anli_r3": lambda: nli_set_items("anli_r3"), "wanli": lambda: nli_set_items("wanli"),
        "scitail": lambda: nli_set_items("scitail"), "control": lambda: nli_set_items("control"),
        "arc_easy": lambda: arc_items("ARC-Easy"), "arc_challenge": lambda: arc_items("ARC-Challenge"),
        "winogrande": winogrande_items, "gsm8k_mc4": lambda: gsm8k_mc_items(4), "gsm8k_mc10": lambda: gsm8k_mc_items(10),
        "gpqa": lambda: gpqa_items(0), "gpqa_fewshot": lambda: gpqa_items(5), "chess": chess_items,
        "hellaswag": hellaswag_items, "mmlu": lambda: mmlu_items(0), "mmlu_fewshot": lambda: mmlu_items(5),
        "gsm8k_rerank4": gsm8k_rerank_items,
    }
    items, counts, missing = [], {}, []
    for t in tasks:
        got = builders[t]()
        counts[t] = len(got)
        if not got:
            missing.append(t)
        items.extend(got)
    info = {"source": "AlexWortega/openjev code/eval.py (MIT) task definitions; data from HF Hub / GPQA GitHub zip",
            "revision": "a20448012c213128955ca0c693e7c943865cab77", "counts": counts, "missing": missing,
            "n_items": len(items), "n_requests": sum(len(i["nli"]["hyps"]) for i in items),
            "expected_counts_neohorse": {"scitail": 2126, "anli_r1": 1000, "anli_r2": 1000, "anli_r3": 1200, "wanli": 5000,
                                         "control": 805, "mnli": 9815 + 9832, "arc_easy": 2376, "arc_challenge": 1172,
                                         "winogrande": 1267, "gsm8k_mc4": 1319, "gsm8k_mc10": 1319, "gpqa": 198,
                                         "gpqa_fewshot": 198, "chess": 500, "hellaswag": 10042, "mmlu": 14042,
                                         "mmlu_fewshot": 14042, "gsm8k_rerank4": 200}}
    return items, info


